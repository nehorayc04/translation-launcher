# The 3 pad slots now render the USER'S OWN PNG artwork (build_assets/controllers,
# the same files embedded in frontend/src/lib/controllerIcons.ts). They are solid
# black, so we draw them as a CSS MASK filled with currentColor - otherwise they'd
# be black-on-black in the dark preview, exactly like in the launcher.
import base64
def _img_mask(name, w=30, h=22):
    uri = 'data:image/png;base64,' + base64.b64encode(
        open('build_assets/controllers/%s.png' % name, 'rb').read()).decode()
    return ('<span style="display:inline-block;width:%dpx;height:%dpx;background-color:currentColor;'
            '-webkit-mask-image:url(%s);mask-image:url(%s);'
            '-webkit-mask-repeat:no-repeat;mask-repeat:no-repeat;'
            '-webkit-mask-size:contain;mask-size:contain;'
            '-webkit-mask-position:center;mask-position:center"></span>' % (w, h, uri, uri))

