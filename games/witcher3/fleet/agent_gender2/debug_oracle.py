import re

_HE_YOU_PL = re.compile(r'(?<![א-ת])את[םן](?![א-ת])')
_HE_VERB_F = re.compile(r'\b(?:צריכה|יכולה|יודעת|מוכנה|חייבת|תוכלי|תדעי|בואי|קחי|תעשי|לכי|בטוחה|מבינה|שומעת|אמרת|תגידי|רוצה)\b')
_HE_YOU_M = re.compile(r'(?<![א-ת])אתה(?![א-ת])')
_HE_VERB_M = re.compile(r'\b(?:צריך|יכול|יודע|מוכן|חייב|תוכל|תדע|בוא|קח|תעשה|בטוח|מבין|שומע|תגיד)\b')

def debug(name, s):
    pl = bool(_HE_YOU_PL.search(s))
    atf = bool(re.search(r'(?<![א-ת])את(?![א-ת])(?!\s+ה)', s))
    vf = bool(_HE_VERB_F.search(s))
    vm = bool(_HE_YOU_M.search(s))
    verbm = bool(_HE_VERB_M.search(s))
    fem = vf or atf
    masc = vm or verbm
    result = he_addressee(s)
    print(f'{name}: pl={pl} atf={atf} vf={vf} youm={vm} verbm={verbm} -> {result}')
    if vf:
        print(f'  vf match: {_HE_VERB_F.findall(s)}')
    if vm:
        print(f'  youm match: {_HE_YOU_M.findall(s)}')
    if verbm:
        print(f'  verbm match: {_HE_VERB_M.findall(s)}')
    if atf:
        m = re.search(r'(?<![א-ת])את(?![א-ת])(?!\s+ה)', s)
        print(f'  atf match at: {repr(s[max(0,m.start()-5):m.end()+5])}')

