# Generates icon-manager.html - the launcher icon inventory + a HUGE Flaticon
# UICONS "Interface icons - Regular Rounded" library (~3.9k), now CATEGORIZED
# (browse by category + search) PLUS a curated OFFLINE gaming/controller set
# (Xbox / PlayStation / Switch / D-pad / analog / face-buttons). Assign to any
# slot by drag OR click; exports icon-changes.json.
#
# It also REFLECTS THE APPLIED STATE: the picks in `icon-changes (4).json`
# (7 nav/tab replacements + 63 button/header/badge additions) are shown as the
# CURRENT icon of each slot, so re-picking exports only the NEW delta.
#
# TARGET groups: existing (15 real icons, REPLACE) · window (titlebar controls) ·
# notify (bell states) · controllers (big Settings silhouettes) · optional (72
# icon-LESS UI spots, ADD).
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))

uicons = json.load(open(os.path.join(HERE, 'uicons_map.json')))
UICONS = sorted(uicons.items())
print('uicons in library:', len(UICONS))

optional = json.load(open(os.path.join(HERE, 'iconless_slots.json'), encoding='utf-8'))
print('optional icon-less slots:', len(optional))

# ── group "app": EVERY other user-facing app icon (inline-svg + emoji glyphs that
# had NO customization option before) - generated by build_app_icons.py from the
# frontend inventory, so the manager now covers essentially every icon in the app.
try:
    APP_ICONS = json.load(open(os.path.join(HERE, 'app_icons.json'), encoding='utf-8'))
except Exception as e:
    APP_ICONS = []
    print('no app_icons.json (', e, ') - run build_app_icons.py first')
print('app icons (extra configurable slots):', len(APP_ICONS))

# ── APPLIED picks (reflect the live state) ──
APPLIED = {}       # id -> UICONS iconName
APPLIED_SVG = {}   # id -> raw svg-upload markup
_chg_path = os.path.join(HERE, 'applied_icon_changes.json')
try:
    for c in json.load(open(_chg_path, encoding='utf-8'))['changes']:
        if c.get('iconName'):
            APPLIED[c['id']] = c['iconName']
        elif c.get('newSvg'):
            APPLIED_SVG[c['id']] = c['newSvg']
    print('applied picks reflected:', len(APPLIED), '+', len(APPLIED_SVG), 'svg-upload')
except Exception as e:
    print('no applied_icon_changes.json (', e, ') - showing pristine current icons')

def cur_svg(target_id, fallback_svg):
    """The CURRENT icon shown in the slot - the applied UICONS glyph if the user
    picked one, else an applied svg-upload, else the pristine inline SVG."""
    name = APPLIED.get(target_id)
    if name:
        return '<i class="fi-rr-%s"></i>' % name
    return APPLIED_SVG.get(target_id) or fallback_svg

