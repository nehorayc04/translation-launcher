# Align escape style and newline representation of Hebrew with English
def align_separators(eng, heb):
    sep_pattern = r'(\\n\\p|\\n\\n|\\n|\n)'
    eng_parts = re.split(sep_pattern, eng)
    heb_parts = re.split(sep_pattern, heb)
    if len(eng_parts) == len(heb_parts):
        for i in range(1, len(heb_parts), 2):
            heb_parts[i] = eng_parts[i]
        return ''.join(heb_parts)
    return heb

