# Helper function to find all formatting tags and placeholders (distinguishing real vs escaped)
def extract_tags(text):
    # Find style tags, icons, voice cues
    tags = re.findall(r'\[.*?\]|%.', text)
    # Count real newlines
    for char in text:
        if char == '\n':
            tags.append(r'\n_real')
        elif char == '\r':
            tags.append(r'\r_real')
    # Count literal backslash escapes
    literal_backslashes = re.findall(r'\\n|\\p|\\r', text)
    tags.extend(literal_backslashes)
    return sorted(tags)

